#!/usr/bin/env python3
"""Rebuild the generated tables of the codemod toolkit from the reviewers' data.

    python3 tables/build_tables.py --api-dir <dir with api_fate.tsv and review_*/> --repo <symplex checkout>

Reads (never writes) the review directory and the repository; writes TSV files beside
this script.  Every generated table starts with a `#` line that names its sources.
The hand-written tables (`error_kinds.tsv`, `core_renames.tsv`, `domain_renames.tsv`,
`number_types.tsv`) are NOT touched: they are the rewrite rules themselves, and a
package owner edits them.

Generated:
  truth_queries.tsv   the yes/no queries (review B's optbool.tsv + fates_B.tsv, with the
                      merged fate of api_fate.tsv): which names the `truth` rules may rewrite
  try_pairs.tsv       review C's plain/try_ pairs with how each is called and whether
                      the name is unique in the public API
  path_moves.tsv      every public non-method path of today and where it lives at 1.0
                      (api_fate.tsv; the retired second paths from review A)
  prelude_moves.tsv   the names that leave the prelude and the path to import them from
  dist_ctors.tsv      Distribution constructor -> parameter record and field order,
                      read from the repository's source
  homonyms.tsv        for every method name a rename rule keys on: the public types that
                      define a method of that name today
"""
import argparse
import collections
import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
csv.field_size_limit(sys.maxsize)

UNIT_TYPES = set(
    """Length Mass Time Current Temperature Area Volume Velocity Acceleration AngularVelocity AngularAcceleration
    Frequency Force Energy Torque Power Momentum AngularMomentum MomentOfInertia Pressure Stiffness Damping Voltage
    Resistance Inductance Capacitance Charge MagneticFlux Dimensionless Angle Qty""".split()
)


# Review B's list (scripts/03_callsites.py): names that also exist with a non-`Option` return on
# common types.  A call of such a name is a site only when its reading shows an `Option<bool>`.
B_AMBIGUOUS = set(
    """contains is_empty is_zero equals query is_identity is_integer is_positive is_negative is_finite is_even
    is_odd is_real is_symmetric is_prime is_squarefree is_irreducible is_subset is_superset is_disjoint is_diagonal
    is_unit is_nonzero is_nonnegative is_nonpositive is_rational is_complex is_open is_closed is_in is_hermitian
    is_stable is_positive_definite is_positive_semidefinite is_orthogonal is_unitary""".split()
)


def read_tsv(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE))


def write(name, header, rows, source):
    p = os.path.join(HERE, name)
    with open(p, "w") as f:
        f.write("# generated by tables/build_tables.py from: %s\n" % source)
        f.write("\t".join(header) + "\n")
        for r in rows:
            f.write("\t".join(str(x) for x in r) + "\n")
    print("wrote %-20s %5d rows" % (name, len(rows)))


def truth_queries(api, fate):
    opt = read_tsv(os.path.join(api, "review_B_truth", "data", "optbool.tsv"))
    fb = read_tsv(os.path.join(api, "review_B_truth", "fates_B.tsv"))
    per = collections.defaultdict(list)
    for r in opt:
        name = r["path"].split("::")[-1]
        f = fate.get(r["path"], {})
        sig = f.get("new_signature", "")
        rules = f.get("rules", "")
        if name in ("to_option", "from", "as_outcome"):
            verdict = "not-a-query"
        elif f.get("change") == "remove" or "B2:REMOVE" in rules:
            verdict = "removed"
        elif "F:PE-MOVE" in rules:
            verdict = "moves-to-Poly"
        elif "Result<bool>" in sig:
            verdict = "result-bool"
        elif "Result<Truth>" in sig:
            verdict = "result-truth"
        elif "-> Truth" in sig:
            verdict = "truth"
        else:
            verdict = "unknown"
        per[name].append((verdict, r["path"], r["kind"]))
    rows = []
    for name in sorted(per):
        items = per[name]
        verdicts = sorted(set(v for v, _p, _k in items))
        fate_s = verdicts[0] if len(verdicts) == 1 else "mixed:" + "+".join(verdicts)
        styles = sorted(set("method" if k == "method" else "free" for _v, _p, k in items))
        rewrite = "yes" if fate_s == "truth" else "no"
        owners = sorted(set(p.split("::")[-2] for _v, p, _k in items if p.split("::")[-2] not in UNIT_TYPES))
        if any(p.split("::")[-2] in UNIT_TYPES for _v, p, _k in items):
            owners.append("(30 unit types)")
        rows.append([name, "Option<bool>", fate_s, rewrite, "+".join(styles), len(items),
                     "yes" if name in B_AMBIGUOUS else "no", ", ".join(owners)])
    # the queries that return a plain bool today and Truth at 1.0 (B2:DEFECT:bool)
    seen = set()
    for r in fb:
        if r["part"] == "2" and r["class"] == "DEFECT:bool":
            name = r["path"].split("::")[-1]
            owner = r["path"].split("::")[-2]
            key = (name, owner in UNIT_TYPES)
            if key in seen:
                continue
            seen.add(key)
            if owner in UNIT_TYPES:
                # the unit copies share their names with Ex::is_zero / Ex::equals (Option<bool>)
                rows.append([name, "bool", "truth", "no", "method", 30, "yes",
                             "(30 unit types): receiver type not known"])
            else:
                rows.append([name, "bool", "truth", "yes", "method" if owner[:1].isupper() else "free", 1, "no",
                             owner])
    write("truth_queries.tsv", ["name", "today", "fate", "rewrite", "call", "items", "ambiguous", "owners"], rows,
          "review_B_truth/data/optbool.tsv, review_B_truth/fates_B.tsv, api_fate.tsv")


def homonym_map(api):
    listing = read_tsv(os.path.join(api, "public_api_0.59.tsv"))
    by = collections.defaultdict(set)
    for r in listing:
        name = r["path"].split("::")[-1]
        owner = r["container"] or r["path"].rsplit("::", 1)[0]
        by[name].add(owner)
    return by


def try_pairs(api, by):
    rows = []
    for r in read_tsv(os.path.join(api, "review_C_refusals", "data", "try_pairs_060.tsv")):
        style = {"method": "method", "free": "free", "assoc": "path", "get2": "method", "closure": "method"}[r["match"]]
        owners = sorted(o for o in by.get(r["plain"], ()) if o not in UNIT_TYPES)
        rows.append([r["class"], r["container"], r["plain"], r["try"], style, len(owners), ", ".join(owners),
                     r["fate"]])
    write("try_pairs.tsv", ["class", "container", "plain", "try", "call", "n_owners", "owners_of_plain_name", "fate"],
          rows, "review_C_refusals/data/try_pairs_060.tsv, public_api_0.59.tsv")


def path_moves(api, fate):
    retired = read_tsv(os.path.join(api, "review_A_surface", "data", "retired_paths.tsv"))
    alt = collections.defaultdict(set)
    for r in retired:
        olds = [p.strip() for p in r["old_paths"].split(" | ") if p.strip()]
        for p in olds:
            for q in olds:
                alt[p].add(q)
    rows = []
    seen = {}
    for path, f in fate.items():
        if f["kind"] == "method":
            continue
        row = [path, f["kind"], f["tier"], f["change"], f["new_path"]]
        seen[path] = row
        rows.append(row)
    extra = []
    for path, row in list(seen.items()):
        for q in sorted(alt.get(path, ())):
            if q not in seen and not q.startswith("symplex::prelude::"):
                extra.append([q, row[1], row[2], row[3], row[4]])
                seen[q] = row
    rows.extend(extra)
    # the five procedural macros are not lines of the listing (API_1.0.md §1.4)
    for old, tier, change, new in (
        ("symplex::expr!", "stable", "keep", "symplex::expr!"),
        ("symplex::eq!", "stable", "keep", "symplex::eq!"),
        ("symplex::matrix!", "stable", "keep", "symplex::matrix!"),
        ("symplex::rule!", "stable", "move", "symplex::rules::rule!"),
        ("symplex::dim!", "experimental", "move", "symplex::experimental::units::dim!"),
    ):
        rows.append([old.rstrip("!"), "macro", tier, change, new.rstrip("!")])
    rows.sort()
    write("path_moves.tsv", ["old_path", "kind", "tier", "change", "new_path"], rows,
          "api_fate.tsv (non-method rows), review_A_surface/data/retired_paths.tsv (second paths)")
    # the prelude
    pre = []
    for r in retired:
        olds = [p.strip() for p in r["old_paths"].split(" | ")]
        names = [p for p in olds if p.startswith("symplex::prelude::")]
        if not names:
            continue
        name = names[0].split("::")[-1]
        listing = [p for p in olds if p in fate]
        f = fate[listing[0]] if listing else None
        pre.append([name, r["kind"], f["tier"] if f else r["tier"].lower(), f["change"] if f else "?",
                    f["new_path"] if f else r["new_canonical_path"]])
    # prelude names that are not items of the listing: the re-exported foreign type and the two
    # procedural macros that leave the prelude (review A, retired_paths.py OLD_PRELUDE; API_1.0.md §1.4)
    pre.append(["Complex64", "foreign", "stable", "move", "symplex::num::Complex64"])
    pre.append(["dim", "macro", "experimental", "move", "symplex::experimental::units::dim"])
    pre.append(["rule", "macro", "stable", "move", "symplex::rules::rule"])
    pre.sort()
    write("prelude_moves.tsv", ["name", "kind", "tier", "change", "new_path"], pre,
          "review_A_surface/data/retired_paths.tsv (old prelude paths), api_fate.tsv (final home)")


def dist_ctors(repo):
    rows = []
    for rel in ("src/domains/stats/continuous.rs", "src/domains/stats/discrete.rs"):
        p = os.path.join(repo, rel)
        if not os.path.isfile(p):
            print("  (skipped %s: not found)" % rel)
            continue
        src = open(p, encoding="utf-8").read()
        for m in re.finditer(r"pub fn (\w+)\(\s*([^)]*)\)\s*->\s*Distribution\s*\{([^}]*\{[^}]*\}[^}]*|[^}]*)\}", src):
            name, params, body = m.group(1), m.group(2), m.group(3)
            pnames = [x.split(":")[0].strip() for x in params.split(",") if x.strip()]
            lit = re.match(r"\s*Distribution::from_family\(\s*(\w+)\s*\{([^}]*)\}\s*\)\s*$", body)
            if lit:
                fields = [x.strip() for x in lit.group(2).split(",") if x.strip()]
                if fields == pnames:
                    rows.append([name, lit.group(1), ",".join(fields), "yes", ""])
                    continue
                rows.append([name, lit.group(1), ",".join(fields), "no",
                             "the record is not built from the parameters one to one"])
                continue
            rec = re.search(r"from_family\(\s*(\w+)", body)
            rows.append([name, rec.group(1) if rec else "?", ",".join(pnames), "no",
                         "the constructor does more than fill a record (read %s)" % rel])
    write("dist_ctors.tsv", ["ctor", "record", "fields_in_argument_order", "rewrite", "note"], rows,
          "src/domains/stats/{continuous,discrete}.rs of the repository (constructor bodies)")


def homonyms(by):
    names = set()
    for fn in ("core_renames.tsv", "domain_renames.tsv"):
        p = os.path.join(HERE, fn)
        if not os.path.isfile(p):
            continue
        for line in open(p):
            if line.startswith("#") or not line.strip():
                continue
            cols = line.rstrip("\n").split("\t")
            if cols[0] == "id":
                continue
            names.add(cols[2])
    rows = []
    for n in sorted(names):
        owners = by.get(n, set())
        units = sorted(o for o in owners if o in UNIT_TYPES)
        others = sorted(o for o in owners if o not in UNIT_TYPES)
        rows.append([n, len(units), ", ".join(others)])
    write("homonyms.tsv", ["method", "unit_copies", "other_owners"], rows,
          "public_api_0.59.tsv, for the old names in core_renames.tsv and domain_renames.tsv")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--api-dir", required=True,
                    help="the directory with api_fate.tsv and the listing public_api_<version>.tsv")
    ap.add_argument("--repo", default=os.path.normpath(os.path.join(HERE, "..", "..", "..")))
    a = ap.parse_args()
    fate = {r["path"]: r for r in read_tsv(os.path.join(a.api_dir, "api_fate.tsv"))}
    by = homonym_map(a.api_dir)
    truth_queries(a.api_dir, fate)
    try_pairs(a.api_dir, by)
    path_moves(a.api_dir, fate)
    dist_ctors(a.repo)
    homonyms(by)


if __name__ == "__main__":
    main()
