#!/usr/bin/env python3
"""Write the public API of the crate as sorted text, one line per item.

Input:  rustdoc's JSON for the library (`api_snapshot.sh` builds it).
Output: `api/<tier>.txt`, one file per tier named in `tiers.txt`.

The crate is walked from its root through every `pub mod` and `pub use`, so an
item is listed under the paths a user can write, not under the file it is
defined in.  Each item gets one line under its canonical path (the shortest
one; `prelude` last) and a `use` line for every other path.

`README.md` beside this file describes the line format and how to read a diff.
Python 3, standard library only.
"""

import argparse
import difflib
import json
import os
import re
import sys

# rustdoc's JSON is unstable: its layout is identified by `format_version`.
# The script refuses a version it has not been checked against, instead of
# printing something subtly different.  To add one: read the changes between
# the two versions in rust-lang/rust `src/rustdoc-json-types/lib.rs`, adapt the
# functions below, regenerate, and review the diff of `api/`.
KNOWN_FORMATS = (61,)

# Auto traits recorded for every type.  rustdoc also reports compiler-internal
# ones (`Freeze`, `UnsafeUnpin`, ...), which come and go with the toolchain and
# cannot be named in stable Rust.
AUTO_TRAITS = ("Send", "Sync", "Unpin", "UnwindSafe", "RefUnwindSafe")

# Marker traits of `core` that derives implement behind the scenes.
IGNORED_CORE_TRAITS = ("StructuralPartialEq", "TrivialClone")

# These names always mean the standard item; anything else of the same name
# (`core::fmt::Result`, a local `Result` alias) is written with its full path.
STD_NAMES = ("core::result::Result", "core::option::Option", "alloc::vec::Vec", "alloc::string::String",
             "alloc::boxed::Box")

HEADER = "# Public API of the crate, tier `%s`: one line per item, sorted.\n" \
         "# Generated by scripts/api_snapshot/api_snapshot.sh - do not edit by hand.\n" \
         "# How to regenerate it and how to read a diff: scripts/api_snapshot/README.md\n"
GENERATED_MARK = "# Generated by scripts/api_snapshot/api_snapshot.sh"

MAX_DEPTH = 12


def fail(message):
    raise SystemExit("api_snapshot: " + message)


def kind_of(item):
    return next(iter(item["inner"]))


def is_doc_hidden(item):
    for attr in item.get("attrs", []):
        text = attr if isinstance(attr, str) else " ".join(str(v) for v in attr.values())
        if re.search(r"\bdoc\s*\([^\]]*\bhidden\b", text):
            return True
    return False


def squeeze(text):
    return " ".join(str(text).split())


def ids_in(node):
    """Ids of the items a piece of the JSON refers to, in a fixed order."""
    if isinstance(node, dict):
        if "id" in node and "path" in node and node["id"] is not None:
            yield node["id"]
        for key in sorted(node):
            if key != "id":
                yield from ids_in(node[key])
    elif isinstance(node, list):
        for child in node:
            yield from ids_in(child)


def single(node, what):
    """The (key, value) of a JSON enum value written as a one-entry object."""
    if not isinstance(node, dict) or len(node) != 1:
        fail("unexpected %s in the rustdoc JSON: %s" % (what, json.dumps(node)[:200]))
    return next(iter(node.items()))


# --------------------------------------------------------------------- walk
class Surface:
    """The items of the crate and every path under which each can be named."""

    def __init__(self, data):
        version = data.get("format_version")
        if version not in KNOWN_FORMATS:
            fail("rustdoc JSON format %r is not one this script knows (%s).\n"
                 "  Use the nightly pinned as API_TOOLCHAIN in .github/workflows/ci.yml, or teach\n"
                 "  the script the new format (see KNOWN_FORMATS in %s)."
                 % (version, ", ".join(map(str, KNOWN_FORMATS)), os.path.basename(__file__)))
        self.index = data["index"]
        self.summaries = data["paths"]
        self.root = data["root"]
        self.crate = self.index[str(self.root)]["name"]
        # (key, path, hidden) in walk order.  `key` is an item id, or
        # ("extern", source, is_glob) for a re-export of another crate's item.
        # `hidden` says that a module or `use` on the way is `#[doc(hidden)]`.
        self.sightings = []
        self.external = {}
        self._walked = set()
        self._walk(self.root, (self.crate,), False, 0)

    def item(self, item_id):
        return self.index.get(str(item_id))

    def is_local(self, item_id):
        return str(item_id) in self.index

    def _walk(self, module_id, path, hidden, depth):
        if (module_id, path) in self._walked or depth > MAX_DEPTH:
            return
        self._walked.add((module_id, path))
        module = self.item(module_id)
        if module is None:
            return
        for child_id in module["inner"]["module"]["items"]:
            child = self.item(child_id)
            if child is None:
                continue
            kind = kind_of(child)
            if kind == "use":
                use = child["inner"]["use"]
                target_id = use.get("id")
                if target_id is None:
                    continue
                via_hidden = hidden or is_doc_hidden(child)
                target = self.item(target_id)
                if target is None:
                    key = ("extern", use["source"], bool(use["is_glob"]))
                    self.external[key] = self.summaries.get(str(target_id))
                    self.sightings.append((key, path + (use["name"],), via_hidden))
                    continue
                target_kind = kind_of(target)
                if use["is_glob"]:
                    if target_kind == "module":
                        self._walk(target_id, path, via_hidden or is_doc_hidden(target), depth + 1)
                    elif target_kind == "enum":
                        for variant_id in target["inner"]["enum"]["variants"]:
                            variant = self.item(variant_id)
                            if variant is not None:
                                self.sightings.append((variant_id, path + (variant["name"],), via_hidden))
                    continue
                here = path + (use["name"],)
                if target_kind == "module":
                    via_hidden = via_hidden or is_doc_hidden(target)
                self.sightings.append((target_id, here, via_hidden))
                if target_kind == "module":
                    self._walk(target_id, here, via_hidden, depth + 1)
            else:
                here = path + (child["name"],)
                via_hidden = hidden or (kind == "module" and is_doc_hidden(child))
                self.sightings.append((child_id, here, via_hidden))
                if kind == "module":
                    self._walk(child_id, here, via_hidden, depth + 1)


# -------------------------------------------------------------------- tiers
class Tiers:
    """`tiers.txt`: which file an item goes to, by path prefix."""

    def __init__(self, text, origin):
        self.order = []      # tier names, the least public first
        self.prefixes = {}   # path -> tier
        self.hidden = None   # tier of doc-hidden items, if there is a rule
        self.default = None
        for number, raw in enumerate(text.splitlines(), 1):
            line = raw.split("#", 1)[0].split()
            if not line:
                continue
            if len(line) != 2 or not re.fullmatch(r"[a-z][a-z0-9_]*", line[0]):
                fail("%s:%d: expected `<tier> <rule>`, got `%s`" % (origin, number, raw.strip()))
            tier, rule = line
            if tier not in self.order:
                self.order.append(tier)
            if rule == "*":
                self.default = tier
            elif rule == "doc(hidden)":
                self.hidden = tier
            elif re.fullmatch(r"\w+(::\w+)*", rule):
                self.prefixes[tuple(rule.split("::"))] = tier
            else:
                fail("%s:%d: a rule is `*`, `doc(hidden)` or a path, got `%s`" % (origin, number, rule))
        if not self.order:
            fail("%s: no tier rules" % origin)

    def of(self, path, hidden):
        if hidden and self.hidden is not None:
            return self.hidden
        for length in range(len(path), 0, -1):
            tier = self.prefixes.get(path[:length])
            if tier is not None:
                return tier
        if self.default is None:
            fail("no tier rule matches `%s`: add a `*` rule to tiers.txt" % "::".join(path))
        return self.default

    def openness(self, tier):
        return self.order.index(tier)


# ----------------------------------------------------------------- snapshot
class Line:
    __slots__ = ("tier", "key", "kind", "text")

    def __init__(self, tier, anchor, rank, kind, text, name=""):
        self.tier = tier
        self.kind = kind
        self.text = "%-8s %s" % (kind, text)
        # Sorted by the item the line belongs to, then by what it is, then by
        # name (so that the methods of a type are in alphabetical order whatever
        # impl block they come from), then by the text.
        self.key = (anchor, rank, name, self.text)


# Order of the lines that belong to one type or trait.
RANK_ITEM, RANK_PART, RANK_ASSOC, RANK_METHOD, RANK_IMPL, RANK_IMPLS = range(6)


class Snapshot:
    def __init__(self, surface, tiers):
        self.s = surface
        self.tiers = tiers
        self.ambiguous = set()
        self._choose_canonical_paths()
        # A type is written by its name alone unless two different items of
        # that name are mentioned somewhere: the first pass finds those names.
        self._build()
        self.ambiguous = {name for name, targets in self.mentions.items() if len(targets) > 1}
        self._build()
        self.qualified = sorted(full for name in self.ambiguous for full in self.mentions[name] if full not in STD_NAMES)

    # ---- paths ---------------------------------------------------------
    def _choose_canonical_paths(self):
        s = self.s
        self.variant_parent = {}
        for item_id, item in s.index.items():
            if kind_of(item) == "enum":
                for variant_id in item["inner"]["enum"]["variants"]:
                    self.variant_parent[variant_id] = int(item_id)
        self.own_hidden = {}
        candidates = {}
        for key, path, via_hidden in s.sightings:
            if isinstance(key, tuple) or key in self.variant_parent:
                continue
            if key not in self.own_hidden:
                self.own_hidden[key] = is_doc_hidden(s.item(key))
            hidden = via_hidden or self.own_hidden[key]
            candidates.setdefault(key, []).append((path, hidden))
        self.canon = {}    # item id -> canonical path
        self.hidden = {}   # item id -> no path to it is free of #[doc(hidden)]
        self.tier = {}
        for key, found in candidates.items():
            def preference(entry):
                path, hidden = entry
                return (-self.tiers.openness(self.tiers.of(path, hidden)), hidden, "prelude" in path, len(path), path)
            path, hidden = min(found, key=preference)
            self.canon[key] = path
            self.hidden[key] = hidden
            self.tier[key] = self.tiers.of(path, hidden)
        self.module_at = {}
        for key, path, _ in s.sightings:
            if not isinstance(key, tuple) and kind_of(s.item(key)) == "module":
                self.module_at.setdefault(path, key)

    def reachable(self, item_id):
        return item_id in self.canon

    def _is_derived(self, path):
        """The path only repeats a second path of the module it goes through."""
        parent = path[:-1]
        module_id = self.module_at.get(parent)
        return module_id is not None and self.canon.get(module_id) != parent

    # ---- names of referenced items -------------------------------------
    def full_name(self, item_id, written):
        if item_id in self.canon:
            return "::".join(self.canon[item_id])
        summary = self.s.summaries.get(str(item_id))
        if summary is not None:
            if summary["crate_id"] == 0:
                self.unnameable.add("::".join(summary["path"]))
            return "::".join(summary["path"])
        return written.rsplit("::", 1)[-1]

    def ref(self, item_id, written):
        full = self.full_name(item_id, written)
        short = full.rsplit("::", 1)[-1]
        self.mentions.setdefault(short, set()).add(full)
        return full if short in self.ambiguous and full not in STD_NAMES else short

    # ---- types ---------------------------------------------------------
    def path(self, node):
        return self.ref(node["id"], node["path"]) + self.generic_args(node.get("args"))

    def generic_args(self, node):
        if node is None:
            return ""
        if node == "return_type_notation":
            return "(..)"
        kind, value = single(node, "generic arguments")
        if kind == "angle_bracketed":
            parts = [self.generic_arg(a) for a in value["args"]]
            parts += [self.constraint(c) for c in value.get("constraints", [])]
            return "<" + ", ".join(parts) + ">" if parts else ""
        if kind == "parenthesized":
            text = "(" + ", ".join(self.ty(t) for t in value["inputs"]) + ")"
            if value.get("output") is not None:
                text += " -> " + self.ty(value["output"])
            return text
        fail("unknown generic arguments `%s`" % kind)

    def generic_arg(self, node):
        if node == "infer":
            return "_"
        kind, value = single(node, "generic argument")
        if kind == "type":
            return self.ty(value)
        if kind == "lifetime":
            return value
        if kind == "const":
            return self.const_expr(value)
        fail("unknown generic argument `%s`" % kind)

    @staticmethod
    def const_expr(node):
        if isinstance(node, str):
            return squeeze(node)
        return squeeze(node.get("expr") or node.get("value") or "_")

    def term(self, node):
        kind, value = single(node, "term")
        return self.ty(value) if kind == "type" else self.const_expr(value)

    def constraint(self, node):
        name = node["name"] + self.generic_args(node.get("args"))
        kind, value = single(node["binding"], "associated item constraint")
        if kind == "equality":
            return name + " = " + self.term(value)
        if kind == "constraint":
            return name + ": " + self.bounds(value)
        fail("unknown associated item constraint `%s`" % kind)

    def higher_ranked(self, params):
        names = self.generic_params(params)
        return "for<" + ", ".join(names) + "> " if names else ""

    def bound(self, node):
        kind, value = single(node, "bound")
        if kind == "trait_bound":
            modifier = {"none": "", "maybe": "?", "maybe_const": "~const "}.get(value.get("modifier", "none"))
            if modifier is None:
                fail("unknown trait bound modifier `%s`" % value["modifier"])
            return modifier + self.higher_ranked(value.get("generic_params", [])) + self.path(value["trait"])
        if kind == "outlives":
            return value
        if kind == "use":
            return "use<" + ", ".join(a if isinstance(a, str) else str(next(iter(a.values()))) for a in value) + ">"
        fail("unknown bound `%s`" % kind)

    def bounds(self, nodes):
        texts = [self.bound(b) for b in nodes]
        if self.dedupe_bounds:
            texts = list(dict.fromkeys(texts))
        return " + ".join(texts)

    def behind_pointer(self, node):
        text = self.ty(node)
        if isinstance(node, dict):
            if "dyn_trait" in node and len(node["dyn_trait"]["traits"]) + bool(node["dyn_trait"].get("lifetime")) > 1:
                return "(" + text + ")"
            if "impl_trait" in node and len(node["impl_trait"]) > 1:
                return "(" + text + ")"
        return text

    def fn_pointer(self, node):
        text = self.higher_ranked(node.get("generic_params", []))
        header = node["header"]
        text += "unsafe " if header["is_unsafe"] else ""
        text += "" if header["abi"] == "Rust" else "extern %s " % json.dumps(self.abi(header["abi"]))
        inputs = [self.ty(t) for _, t in node["sig"]["inputs"]]
        if node["sig"].get("is_c_variadic"):
            inputs.append("...")
        text += "fn(" + ", ".join(inputs) + ")"
        if node["sig"].get("output") is not None:
            text += " -> " + self.ty(node["sig"]["output"])
        return text

    @staticmethod
    def abi(node):
        if isinstance(node, str):
            return node
        kind, value = single(node, "ABI")
        return kind + ("-unwind" if isinstance(value, dict) and value.get("unwind") else "")

    def ty(self, node):
        if node is None:
            return "()"
        if node == "infer":
            return "_"
        kind, value = single(node, "type")
        if kind == "resolved_path":
            return self.path(value)
        if kind in ("generic", "primitive"):
            return value
        if kind == "tuple":
            return "(" + ", ".join(self.ty(t) for t in value) + ("," if len(value) == 1 else "") + ")"
        if kind == "slice":
            return "[" + self.ty(value) + "]"
        if kind == "array":
            return "[%s; %s]" % (self.ty(value["type"]), squeeze(value["len"]))
        if kind == "borrowed_ref":
            lifetime = value["lifetime"] + " " if value.get("lifetime") else ""
            return "&" + lifetime + ("mut " if value["is_mutable"] else "") + self.behind_pointer(value["type"])
        if kind == "raw_pointer":
            return "*" + ("mut " if value["is_mutable"] else "const ") + self.behind_pointer(value["type"])
        if kind == "impl_trait":
            return "impl " + self.bounds(value)
        if kind == "dyn_trait":
            parts = [self.higher_ranked(t.get("generic_params", [])) + self.path(t["trait"]) for t in value["traits"]]
            if value.get("lifetime"):
                parts.append(value["lifetime"])
            return "dyn " + " + ".join(parts)
        if kind == "qualified_path":
            owner = self.ty(value["self_type"])
            name = value["name"] + self.generic_args(value.get("args"))
            trait = value.get("trait")
            if trait is not None and trait.get("id") is not None:
                return "<%s as %s>::%s" % (owner, self.path(trait), name)
            return "%s::%s" % (owner, name)
        if kind == "function_pointer":
            return self.fn_pointer(value)
        if kind == "pat":
            return self.ty(value["type"])
        fail("unknown kind of type `%s` in the rustdoc JSON" % kind)

    # ---- generics ------------------------------------------------------
    def generic_params(self, params):
        out = []
        for param in params:
            kind, value = single(param["kind"], "generic parameter")
            if kind == "lifetime":
                out.append(param["name"] + (": " + " + ".join(value["outlives"]) if value.get("outlives") else ""))
            elif kind == "type":
                if value.get("is_synthetic"):
                    continue   # the parameter rustdoc invents for an `impl Trait` argument
                text = param["name"]
                if value.get("bounds"):
                    text += ": " + self.bounds(value["bounds"])
                if value.get("default") is not None:
                    text += " = " + self.ty(value["default"])
                out.append(text)
            elif kind == "const":
                text = "const %s: %s" % (param["name"], self.ty(value["type"]))
                if value.get("default") is not None:
                    text += " = " + self.const_expr(value["default"])
                out.append(text)
            else:
                fail("unknown kind of generic parameter `%s`" % kind)
        return out

    def angle(self, params):
        names = self.generic_params(params)
        return "<" + ", ".join(names) + ">" if names else ""

    def where(self, *predicate_lists):
        out = []
        for predicates in predicate_lists:
            for predicate in predicates:
                kind, value = single(predicate, "where predicate")
                if kind == "bound_predicate":
                    out.append(self.higher_ranked(value.get("generic_params", [])) + self.ty(value["type"])
                               + ": " + self.bounds(value["bounds"]))
                elif kind == "lifetime_predicate":
                    out.append(value["lifetime"] + ": " + " + ".join(value["outlives"]))
                elif kind == "eq_predicate":
                    out.append(self.ty(value["lhs"]) + " == " + self.term(value["rhs"]))
                else:
                    fail("unknown where predicate `%s`" % kind)
        return " where " + ", ".join(out) if out else ""

    # ---- pieces of lines -----------------------------------------------
    def markers(self, item, extra=()):
        out = list(extra)
        for attr in item.get("attrs", []):
            if attr == "non_exhaustive":
                out.append("#[non_exhaustive]")
            elif isinstance(attr, dict) and "must_use" in attr:
                out.append("#[must_use]")
        if item.get("deprecation") is not None:
            out.append("#[deprecated]")
        if is_doc_hidden(item):
            out.append("#[doc(hidden)]")
        return "  " + " ".join(out) if out else ""

    def receiver(self, node):
        if node == {"generic": "Self"}:
            return "self"
        if isinstance(node, dict) and "borrowed_ref" in node and node["borrowed_ref"]["type"] == {"generic": "Self"}:
            ref = node["borrowed_ref"]
            lifetime = ref["lifetime"] + " " if ref.get("lifetime") else ""
            return "&" + lifetime + ("mut " if ref["is_mutable"] else "") + "self"
        return "self: " + self.ty(node)

    def signature(self, function, outer_where=()):
        """`<T>(a: A, b: B) -> R where ...` and the qualifiers of the function."""
        sig = function["sig"]
        inputs = []
        for position, (name, node) in enumerate(sig["inputs"]):
            if position == 0 and name == "self":
                inputs.append(self.receiver(node))
            else:
                inputs.append(squeeze(name) + ": " + self.ty(node))
        if sig.get("is_c_variadic"):
            inputs.append("...")
        text = self.angle(function["generics"]["params"]) + "(" + ", ".join(inputs) + ")"
        if sig.get("output") is not None:
            text += " -> " + self.ty(sig["output"])
        text += self.where(outer_where, function["generics"]["where_predicates"])
        header = function["header"]
        qualifiers = [word for word, on in (("[const]", header["is_const"]), ("[async]", header["is_async"]),
                                            ("[unsafe]", header["is_unsafe"])) if on]
        if header["abi"] != "Rust":
            qualifiers.append("[extern %s]" % json.dumps(self.abi(header["abi"])))
        return text, qualifiers

    @staticmethod
    def macro_arms(source):
        """The matchers of a `macro_rules!` as rustdoc prints them, without optional white space."""
        text = squeeze(source)
        found = re.fullmatch(r"macro_rules!\s*\S+\s*\{(.*)\}", text)
        words = (found.group(1) if found else text).split()
        out = ""
        for word in words:
            if out and re.match(r"[\w']", out[-1]) and re.match(r"[\w']", word[0]):
                out += " "
            out += word
        return out

    # ---- lines ---------------------------------------------------------
    def _add(self, tier, anchor, rank, kind, text, name=""):
        self.lines.append(Line(tier, anchor, rank, kind, text, name))

    def _member(self, owner_path, owner_hidden, member, rank, kind, text):
        hidden = owner_hidden or is_doc_hidden(member)
        name = member["name"] or "_"
        self._add(self.tiers.of(owner_path + (name,), hidden), owner_path, rank, kind, text, name)

    def _build(self):
        self.lines = []
        self.mentions = {}
        self.unnameable = set()
        self.compact = {}
        self.skipped_impls = 0
        self.dedupe_bounds = False
        s = self.s
        for item_id, path in self.canon.items():
            self._item_lines(item_id, s.item(item_id), path)
        for item_id, item in s.index.items():
            if kind_of(item) == "impl" and item.get("crate_id", 0) == 0:
                self._impl_lines(item)
        for owner_id, traits in self.compact.items():
            path = self.canon[owner_id]
            self._add(self.tier[owner_id], path, RANK_IMPLS, "impls", "::".join(path) + ": " + " + ".join(sorted(traits)))
        self._alias_lines()

    def _item_lines(self, item_id, item, path):
        kind = kind_of(item)
        inner = item["inner"][kind]
        name = "::".join(path)
        tier = self.tier[item_id]
        hidden = self.hidden[item_id]
        if kind == "module":
            self._add(tier, path, RANK_ITEM, "mod", name + self.markers(item))
        elif kind == "function":
            text, qualifiers = self.signature(inner)
            self._add(tier, path, RANK_ITEM, "fn", name + text + self.markers(item, qualifiers))
        elif kind == "constant":
            self._add(tier, path, RANK_ITEM, "const", name + ": " + self.ty(inner["type"]) + self.markers(item))
        elif kind == "static":
            mutable = "mut " if inner.get("is_mutable") else ""
            self._add(tier, path, RANK_ITEM, "static", name + ": " + mutable + self.ty(inner["type"]) + self.markers(item))
        elif kind == "type_alias":
            text = name + self.angle(inner["generics"]["params"]) + " = " + self.ty(inner["type"])
            self._add(tier, path, RANK_ITEM, "type", text + self.where(inner["generics"]["where_predicates"]) + self.markers(item))
        elif kind in ("macro", "proc_macro"):
            arms = " " + self.macro_arms(inner) if isinstance(inner, str) else ""
            self._add(tier, path, RANK_ITEM, "macro", name + "!" + arms + self.markers(item))
        elif kind in ("struct", "union"):
            self._struct_lines(item, kind, inner, path, tier, hidden)
        elif kind == "enum":
            self._enum_lines(item, inner, path, tier, hidden)
        elif kind == "trait":
            self._trait_lines(item, inner, path, tier, hidden)
        else:
            fail("do not know how to print a public `%s` (%s)" % (kind, name))

    def _struct_lines(self, item, kind, inner, path, tier, hidden):
        name = "::".join(path)
        generics = inner["generics"]
        text = name + self.angle(generics["params"])
        shape = inner["kind"] if kind == "struct" else {"plain": inner}
        extra = []
        fields = []
        if shape == "unit":
            extra.append("[unit]")
        elif "tuple" in shape:
            parts = []
            for field_id in shape["tuple"]:
                field = self.s.item(field_id) if field_id is not None else None
                parts.append("_" if field is None else self.ty(field["inner"]["struct_field"]))
            text += "(" + ", ".join(parts) + ")"
        else:
            fields = [self.s.item(field_id) for field_id in shape["plain"]["fields"]]
            if shape["plain"]["has_stripped_fields"]:
                extra.append("[private fields]")
            elif not fields:
                extra.append("[no fields]")
        text += self.where(generics["where_predicates"])
        self._add(tier, path, RANK_ITEM, kind, text + self.markers(item, extra))
        for field in fields:
            if field is not None:
                line = "%s::%s: %s" % (name, field["name"], self.ty(field["inner"]["struct_field"]))
                self._member(path, hidden, field, RANK_PART, "field", line + self.markers(field))

    def _enum_lines(self, item, inner, path, tier, hidden):
        name = "::".join(path)
        generics = inner["generics"]
        text = name + self.angle(generics["params"]) + self.where(generics["where_predicates"])
        extra = ["[hidden variants]"] if inner.get("has_stripped_variants") else []
        self._add(tier, path, RANK_ITEM, "enum", text + self.markers(item, extra))
        for variant_id in inner["variants"]:
            variant = self.s.item(variant_id)
            if variant is None:
                continue
            shape = variant["inner"]["variant"]["kind"]
            line = "%s::%s" % (name, variant["name"])
            if shape == "plain":
                pass
            elif "tuple" in shape:
                parts = []
                for field_id in shape["tuple"]:
                    field = self.s.item(field_id) if field_id is not None else None
                    parts.append("_" if field is None else self.ty(field["inner"]["struct_field"]))
                line += "(" + ", ".join(parts) + ")"
            else:
                parts = []
                for field_id in shape["struct"]["fields"]:
                    field = self.s.item(field_id)
                    if field is not None:
                        parts.append("%s: %s" % (field["name"], self.ty(field["inner"]["struct_field"])))
                if shape["struct"]["has_stripped_fields"]:
                    parts.append("..")
                line += " { " + ", ".join(parts) + " }"
            discriminant = variant["inner"]["variant"].get("discriminant")
            if discriminant is not None:
                line += " = " + squeeze(discriminant.get("expr") or discriminant.get("value"))
            self._member(path, hidden, variant, RANK_PART, "variant", line + self.markers(variant))

    def _is_sealed(self, inner):
        """A supertrait that has no public path: nobody outside can implement the trait."""
        supertraits = list(ids_in(inner["bounds"]))
        for predicate in inner["generics"]["where_predicates"]:
            bound = predicate.get("bound_predicate")
            if bound is not None and bound["type"] == {"generic": "Self"}:
                supertraits += [b["trait_bound"]["trait"]["id"] for b in bound["bounds"] if "trait_bound" in b]
        return any(self.s.is_local(t) and not self.reachable(t) for t in supertraits)

    def _trait_lines(self, item, inner, path, tier, hidden):
        name = "::".join(path)
        generics = inner["generics"]
        text = name + self.angle(generics["params"])
        if inner["bounds"]:
            text += ": " + self.bounds(inner["bounds"])
        text += self.where(generics["where_predicates"])
        extra = [word for word, on in (("[unsafe]", inner["is_unsafe"]), ("[auto]", inner["is_auto"]),
                                       ("[sealed]", self._is_sealed(inner)),
                                       ("[dyn-compatible]", inner.get("is_dyn_compatible"))) if on]
        self._add(tier, path, RANK_ITEM, "trait", text + self.markers(item, extra))
        for member_id in inner["items"]:
            member = self.s.item(member_id)
            if member is not None:
                self._assoc_line(member, name, path, hidden, in_trait=True)

    def _assoc_line(self, member, owner_text, owner_path, owner_hidden, in_trait, prefix="", outer_where=()):
        kind = kind_of(member)
        inner = member["inner"][kind]
        line = "%s%s::%s" % (prefix, owner_text, member["name"])
        if kind == "function":
            text, extra = self.signature(inner, outer_where)
            if in_trait:
                extra.append("[provided]" if inner["has_body"] else "[required]")
            self._member(owner_path, owner_hidden, member, RANK_METHOD, "method", line + text + self.markers(member, extra))
        elif kind == "assoc_const":
            extra = []
            if in_trait:
                extra.append("[provided]" if inner.get("value") is not None else "[required]")
            line += ": " + self.ty(inner["type"]) + self.where(outer_where)
            self._member(owner_path, owner_hidden, member, RANK_ASSOC, "const", line + self.markers(member, extra))
        elif kind == "assoc_type":
            extra = []
            line += self.angle(inner["generics"]["params"])
            if inner.get("bounds"):
                line += ": " + self.bounds(inner["bounds"])
            if inner.get("type") is not None:
                line += " = " + self.ty(inner["type"])
            if in_trait:
                extra.append("[provided]" if inner.get("type") is not None else "[required]")
            line += self.where(outer_where, inner["generics"]["where_predicates"])
            self._member(owner_path, owner_hidden, member, RANK_ASSOC, "type", line + self.markers(member, extra))
        else:
            fail("do not know how to print the associated item `%s` of %s" % (kind, owner_text))

    # ---- impl blocks ---------------------------------------------------
    def _expand_alias(self, node):
        """`Alias<A>` -> the type it stands for, when the alias is local."""
        for _ in range(8):
            if not (isinstance(node, dict) and "resolved_path" in node):
                break
            target = self.s.item(node["resolved_path"]["id"])
            if target is None or kind_of(target) != "type_alias":
                break
            alias = target["inner"]["type_alias"]
            args = (node["resolved_path"].get("args") or {}).get("angle_bracketed", {}).get("args", [])
            names = [p["name"] for p in alias["generics"]["params"] if "lifetime" not in p["kind"]]
            values = [a for a in args if isinstance(a, dict) and "lifetime" not in a]
            mapping = {n: v["type"] for n, v in zip(names, values) if "type" in v}
            node = self._substitute(alias["type"], mapping)
        return node

    def _substitute(self, node, mapping):
        if isinstance(node, dict):
            if set(node) == {"generic"} and node["generic"] in mapping:
                return mapping[node["generic"]]
            return {k: self._substitute(v, mapping) for k, v in node.items()}
        if isinstance(node, list):
            return [self._substitute(v, mapping) for v in node]
        return node

    def self_type(self, node):
        """The type an impl block is for, its head written by its full canonical path."""
        if isinstance(node, dict) and "borrowed_ref" in node:
            ref = node["borrowed_ref"]
            lifetime = ref["lifetime"] + " " if ref.get("lifetime") else ""
            return "&" + lifetime + ("mut " if ref["is_mutable"] else "") + self.self_type(ref["type"])
        if isinstance(node, dict) and "resolved_path" in node and node["resolved_path"]["id"] in self.canon:
            head = node["resolved_path"]
            self.ref(head["id"], head["path"])
            return "::".join(self.canon[head["id"]]) + self.generic_args(head.get("args"))
        return self.ty(node)

    def _impl_lines(self, item):
        s = self.s
        impl = item["inner"]["impl"]
        if impl.get("blanket_impl") is not None:
            return   # `impl<T> From<T> for T` and the like, repeated by rustdoc for every type
        trait = impl.get("trait")
        mentioned = list(ids_in(impl["for"])) + (list(ids_in(trait)) if trait is not None else [])
        local = [i for i in mentioned if s.is_local(i)]
        if any(not self.reachable(i) for i in local):
            self.skipped_impls += 1
            return   # for, or of, something that has no public path
        generics = impl["generics"]
        prefix = self.angle(generics["params"])
        prefix += " " if prefix else ""
        hidden = is_doc_hidden(item) or any(self.hidden[i] for i in local)

        if trait is None:
            target = self._expand_alias(impl["for"])
            if isinstance(target, dict) and "resolved_path" in target and self.reachable(target["resolved_path"]["id"]):
                owner_id = target["resolved_path"]["id"]
                owner_text = self.self_type(target)
            elif isinstance(target, dict) and "dyn_trait" in target and self.reachable(target["dyn_trait"]["traits"][0]["trait"]["id"]):
                owner_id = target["dyn_trait"]["traits"][0]["trait"]["id"]
                owner_text = "<" + self.ty(target) + ">"
            else:
                fail("inherent impl for a type the script cannot place: %s" % json.dumps(impl["for"])[:200])
            owner_path = self.canon[owner_id]
            for member_id in impl["items"]:
                member = s.item(member_id)
                if member is not None and member.get("visibility") == "public":
                    self._assoc_line(member, owner_text, owner_path, hidden, in_trait=False,
                                     prefix=prefix, outer_where=generics["where_predicates"])
            return

        trait_id = trait["id"]
        trait_name = self.full_name(trait_id, trait["path"]).rsplit("::", 1)[-1]
        summary = s.summaries.get(str(trait_id)) or {}
        if impl.get("is_synthetic") and trait_name not in AUTO_TRAITS:
            return
        if summary.get("path", [""])[0] == "core" and trait_name in IGNORED_CORE_TRAITS:
            return

        # Where the line is sorted: with the type the impl is for; for a
        # foreign type, with the first local item the header names.
        head = impl["for"]
        while isinstance(head, dict) and "borrowed_ref" in head:
            head = head["borrowed_ref"]["type"]
        head = self._expand_alias(head)
        if not (isinstance(head, dict) and "resolved_path" in head and self.reachable(head["resolved_path"]["id"])):
            if not local:
                fail("impl that names no item of this crate: %s" % json.dumps(impl["for"])[:200])
            head = self._expand_alias({"resolved_path": {"id": local[0], "path": "", "args": None}})
        if isinstance(head, dict) and "resolved_path" in head and self.reachable(head["resolved_path"]["id"]):
            owner_id = head["resolved_path"]["id"]
        else:
            owner_id = local[0]
        owner_path = self.canon[owner_id]
        tier = min([self.tier[i] for i in local] + [self.tier[owner_id]], key=self.tiers.openness)
        if hidden and self.tiers.hidden is not None:
            tier = self.tiers.hidden

        assoc = []
        for member_id in impl["items"]:
            member = s.item(member_id)
            if member is None:
                continue
            kind = kind_of(member)
            if kind == "assoc_type":
                assoc.append("type %s%s = %s" % (member["name"], self.angle(member["inner"][kind]["generics"]["params"]),
                                                  self.ty(member["inner"][kind]["type"])))
            elif kind == "assoc_const":
                assoc.append("const %s: %s" % (member["name"], self.ty(member["inner"][kind]["type"])))

        direct = impl["for"].get("resolved_path") if isinstance(impl["for"], dict) else None
        plain_params = all(
            ("type" in p["kind"] and not p["kind"]["type"].get("bounds") and p["kind"]["type"].get("default") is None)
            or ("lifetime" in p["kind"] and not p["kind"]["lifetime"].get("outlives"))
            for p in generics["params"])
        own_params = [{"lifetime": p["name"]} if "lifetime" in p["kind"] else {"type": {"generic": p["name"]}}
                      for p in generics["params"]]
        if (direct is not None and direct["id"] == owner_id and not s.is_local(trait_id) and trait.get("args") is None
                and not assoc and not impl.get("is_negative") and not impl.get("is_unsafe") and not is_doc_hidden(item)
                and plain_params and not generics["where_predicates"]
                and ((direct.get("args") or {}).get("angle_bracketed", {}).get("args", []) == own_params)):
            # `impl Clone for T` with nothing to say beyond the trait's name:
            # collected into the one `impls` line of the type.
            self.compact.setdefault(owner_id, set()).add(self.ref(trait_id, trait["path"]))
            return

        trait_text = self.path(trait)
        text = prefix + ("!" if impl.get("is_negative") else "") + trait_text + " for " + self.self_type(impl["for"])
        # rustdoc writes the conditions of the auto-trait impls it works out
        # itself with repeated bounds (`T: Send + Send`).
        self.dedupe_bounds = bool(impl.get("is_synthetic"))
        text += self.where(generics["where_predicates"])
        self.dedupe_bounds = False
        if assoc:
            text += " { " + "; ".join(sorted(assoc)) + " }"
        extra = ["[unsafe]"] if impl.get("is_unsafe") else []
        self._add(tier, owner_path, RANK_IMPL, "impl", text + self.markers(item, extra), trait_text)

    # ---- second paths --------------------------------------------------
    def _alias_lines(self):
        s = self.s
        seen = set()
        for key, path, via_hidden in s.sightings:
            if (key, path) in seen:
                continue
            seen.add((key, path))
            if isinstance(key, tuple):
                summary = s.external.get(key) or {}
                kind = summary.get("kind", "item")
                bang = "!" if kind in ("macro", "proc_macro") else ""
                target = "::" + "::".join(summary["path"]) if summary.get("path") else "::" + key[1]
                star = "::*" if key[2] else ""
                text = "%s%s%s = %s%s%s  [extern %s]" % ("::".join(path[:-1] if key[2] else path), star, bang, target, star, bang, kind)
                self._add(self.tiers.of(path, via_hidden), path, RANK_ITEM, "use", text)
                continue
            if key in self.variant_parent:
                parent = self.variant_parent[key]
                if not self.reachable(parent):
                    continue
                target = self.canon[parent] + (s.item(key)["name"],)
                hidden = via_hidden
            else:
                target = self.canon[key]
                hidden = via_hidden or self.own_hidden[key]
            if path == target or self._is_derived(path):
                continue
            bang = "!" if kind_of(s.item(key)) in ("macro", "proc_macro") else ""
            text = "%s%s = %s%s" % ("::".join(path), bang, "::".join(target), bang)
            self._add(self.tiers.of(path, hidden), path, RANK_ITEM, "use", text)

    # ---- output --------------------------------------------------------
    def files(self):
        """{file name: text} for every tier of the rules, empty tiers included."""
        by_tier = {tier: [] for tier in self.tiers.order}
        for line in self.lines:
            by_tier[line.tier].append(line)
        out = {}
        for tier, lines in by_tier.items():
            texts = [line.text for line in sorted(lines, key=lambda l: l.key)]
            out[tier + ".txt"] = HEADER % tier + "".join(text + "\n" for text in texts)
        return out

    def summary(self):
        rows = []
        for tier in self.tiers.order:
            counts = {}
            for line in self.lines:
                if line.tier == tier:
                    counts[line.kind] = counts.get(line.kind, 0) + 1
            rows.append("%s.txt: %d lines (%s)" % (tier, sum(counts.values()),
                                                  ", ".join("%s %d" % kv for kv in sorted(counts.items()))))
        if self.qualified:
            rows.append("written with their full path, because another item has the same name: " + ", ".join(self.qualified))
        if self.unnameable:
            rows.append("%d items without a public path are named in public signatures (list them with --verbose)" % len(self.unnameable))
        if self.skipped_impls:
            rows.append("%d impl blocks left out: they are for, or of, an item without a public path" % self.skipped_impls)
        return rows


# --------------------------------------------------------------------- main
def generated_files(directory):
    """The snapshot files present in `directory` (recognised by their header)."""
    found = {}
    if os.path.isdir(directory):
        for name in sorted(os.listdir(directory)):
            full = os.path.join(directory, name)
            if name.endswith(".txt") and os.path.isfile(full):
                with open(full, encoding="utf-8") as handle:
                    text = handle.read()
                if GENERATED_MARK in text[:400]:
                    found[name] = text
    return found


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(os.path.dirname(here))
    parser = argparse.ArgumentParser(description="Write, or with --check verify, the API snapshot in api/.")
    parser.add_argument("--json", default=os.path.join(root, "target", "doc", "symplex.json"),
                        help="rustdoc JSON of the library (default: target/doc/symplex.json)")
    parser.add_argument("--out", default=os.path.join(root, "api"), help="directory of the snapshot files (default: api/)")
    parser.add_argument("--tiers", default=os.path.join(here, "tiers.txt"), help="tier rules (default: tiers.txt beside the script)")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 and print the diff if api/ is out of date")
    parser.add_argument("--verbose", action="store_true", help="also list the items without a public path that signatures name")
    args = parser.parse_args()

    with open(args.json, encoding="utf-8") as handle:
        surface = Surface(json.load(handle))
    with open(args.tiers, encoding="utf-8") as handle:
        tiers = Tiers(handle.read(), args.tiers)
    snapshot = Snapshot(surface, tiers)
    wanted = snapshot.files()
    present = generated_files(args.out)

    if args.check:
        different = False
        for name in sorted(set(wanted) | set(present)):
            old = present.get(name, "").splitlines()
            new = wanted.get(name, "").splitlines()
            if old == new:
                continue
            different = True
            shown = os.path.join(os.path.relpath(args.out, root), name)
            if name not in wanted:
                print("%s is checked in, but no tier of tiers.txt writes it any more" % shown)
                continue
            for row in difflib.unified_diff(old, new, shown + " (checked in)", shown + " (this tree)", lineterm="", n=0):
                print(row)
        if different:
            print("\nThe public API of this tree differs from the snapshot in api/ (the lines above:\n"
                  "`-` is what is checked in, `+` is what the code says now).  If the change is\n"
                  "intended, run\n\n    scripts/api_snapshot/api_snapshot.sh\n\n"
                  "and commit the changed files under api/ with your change, so that the reviewer\n"
                  "sees it.  How to read the lines: scripts/api_snapshot/README.md")
            return 1
        print("api/ is up to date: " + "; ".join(snapshot.summary()[:len(tiers.order)]))
        return 0

    os.makedirs(args.out, exist_ok=True)
    for name, text in wanted.items():
        with open(os.path.join(args.out, name), "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    for name in present:
        if name not in wanted:
            os.remove(os.path.join(args.out, name))
            print("removed %s (no tier of tiers.txt writes it any more)" % name)
    for row in snapshot.summary():
        print(row)
    if args.verbose:
        for name in sorted(snapshot.unnameable):
            print("  no public path: " + name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
