#!/usr/bin/env python3
"""Generate the seed set of the nightly statistics oracle (scripts/stats_oracle/README.md).

    python3 scripts/stats_oracle/gen_cases.py            # (re)write cases/{families,kernels,tests,models}.tsv
    python3 scripts/stats_oracle/gen_cases.py --check    # exit 1 if the committed files differ

The set is a pure function of SEED and this file (standard library only), so a
change to the seed set is a reviewed diff of the case files.  Other case files
in cases/ (hand-written, or exported by a hunter) are read by the oracle as
well; this script only owns the four files it writes.
"""
import math
import random
import sys
from fractions import Fraction as F
from pathlib import Path

SEED = 20261015
HERE = Path(__file__).resolve().parent
OUT = HERE / "cases"
HEADER = (
    "# Generated by scripts/stats_oracle/gen_cases.py (seed {seed}); do not edit by hand.\n"
    "# id\tkind\ttarget\tparams\tmethod\targ\n"
)


def q(v):
    """An exact rational as `N` or `N/D`."""
    v = F(v)
    return str(v.numerator) if v.denominator == 1 else f"{v.numerator}/{v.denominator}"


class Gen:
    def __init__(self, seed):
        self.r = random.Random(seed)

    def choice(self, xs):
        return xs[self.r.randrange(len(xs))]

    def lu(self, lo, hi, digits=3):
        """Log-uniform exact rational in [10^lo, 10^hi] with `digits` significant digits."""
        e = self.r.uniform(lo, hi)
        k = math.floor(e)
        m = round(10 ** (e - k) * 10 ** (digits - 1))
        return F(m, 10 ** (digits - 1)) * F(10) ** k

    def pos(self):
        """A positive scale-like parameter: mostly moderate, sometimes tiny or huge."""
        return self.choice([
            F(self.r.randint(1, 20)),
            F(self.r.randint(1, 99), 10),
            F(2 * self.r.randint(0, 9) + 1, 2),
            self.lu(-2, 2),
            self.lu(-6, -2),
            self.lu(2, 6),
        ])

    def shape(self):
        """A shape parameter: moderate, half-integers, small (< 1) and large."""
        return self.choice([
            F(self.r.randint(1, 12)),
            F(2 * self.r.randint(0, 12) + 1, 2),
            F(self.r.randint(1, 9), 10),
            self.lu(-1, 1),
            self.lu(1, 3),
            self.lu(3, 6),
        ])

    def real(self):
        v = self.pos()
        return self.choice([F(0), v, -v])

    def prob(self):
        return self.choice([
            F(1, 2),
            F(self.r.randint(1, 99), 100),
            F(1, 10 ** self.r.randint(3, 12)),
            1 - F(1, 10 ** self.r.randint(3, 12)),
            F(self.r.randint(1, 999), 1000),
        ])

    def level(self):
        """A probability level as an f64 repr (quantile_f64 / isf_f64)."""
        return self.choice([
            "0.5", "0.025", "0.975", "0.9", "0.1", "1e-10", "1e-100", "0.999999",
            repr(self.r.random()), repr(10 ** -self.r.uniform(1, 300)),
        ])


CONT = {
    # name: (param maker, has closed quantile, has closed mgf, location/scale of x)
    "normal": "loc_scale",
    "uniform": "uniform",
    "exponential": "rate",
    "gamma": "shape_scale",
    "chi_squared": "dof",
    "beta": "two_shapes",
    "cauchy": "loc_scale",
    "laplace": "loc_scale",
    "logistic": "loc_scale",
    "log_normal": "log_normal",
    "student_t": "dof",
    "f": "two_dofs",
    "weibull": "scale_shape",
    "pareto": "scale_shape",
    "triangular": "triangular",
}
DISC = ["bernoulli", "binomial", "poisson", "geometric", "negative_binomial", "hypergeometric",
        "discrete_uniform", "finite"]
CLOSED_QUANTILE = {"normal", "uniform", "exponential", "cauchy", "laplace", "logistic", "log_normal",
                   "weibull", "pareto", "triangular"}
# Families whose mgf has a closed form at every t (or a known abscissa), so the
# nightly can afford it; the rest go through quadrature and are left to hunters.
MGF = {"normal", "uniform", "exponential", "gamma", "chi_squared", "laplace", "logistic", "triangular",
       "bernoulli", "binomial", "poisson", "geometric", "negative_binomial", "discrete_uniform", "finite"}
CF = MGF | {"cauchy"}
NO_ENTROPY = {"hypergeometric", "negative_binomial"}


def family_params(g, fam):
    """(params, location, scale) with exact rationals."""
    if fam in ("normal", "cauchy", "laplace", "logistic"):
        m, s = g.real(), g.pos()
        return [m, s], m, s
    if fam == "uniform":
        a, w = g.real(), g.pos()
        return [a, a + w], a, w
    if fam == "exponential":
        r = g.pos()
        return [r], F(0), 1 / r
    if fam == "gamma":
        k, th = g.shape(), g.pos()
        return [k, th], F(0), k * th
    if fam == "chi_squared":
        k = g.shape()
        return [k], F(0), k
    if fam == "beta":
        return [g.shape(), g.shape()], F(0), F(1)
    if fam == "log_normal":
        mu = g.choice([F(0), F(g.r.randint(-4, 4), g.r.randint(1, 4))])
        s = g.choice([F(1, 4), F(1, 2), F(1), F(3, 2), F(2), F(1, 10)])
        return [mu, s], F(0), F(1)
    if fam == "student_t":
        n = g.shape()
        return [n], F(0), F(1)
    if fam == "f":
        return [g.shape(), g.shape()], F(0), F(1)
    if fam == "weibull":
        lam, k = g.pos(), g.shape()
        return [lam, k], F(0), lam
    if fam == "pareto":
        xm, a = g.pos(), g.shape()
        return [xm, a], xm, xm
    if fam == "triangular":
        a, w = g.real(), g.pos()
        c = g.choice([a, a + w, a + w * F(g.r.randint(1, 9), 10)])
        return [a, a + w, c], a, w
    if fam == "bernoulli":
        return [g.prob()], F(0), F(1)
    if fam == "binomial":
        n = g.choice([0, 1, 2, 5, 10, 30, 100, 1000, 10 ** 6])
        return [F(n), g.prob()], F(0), F(max(n, 1))
    if fam == "poisson":
        lam = g.choice([F(1, 10), F(1), F(7, 2), F(20), F(1, 1000), F(500, 3), F(100000, 7), g.lu(-3, 6)])
        return [lam], lam, F(1)
    if fam == "geometric":
        p = g.prob()
        return [p], F(1), 1 / p
    if fam == "negative_binomial":
        # The mean stays below 10^7: beyond, the f64 quantile's exact search through the incomplete
        # beta takes minutes (negative_binomial(67200, 10^-6).quantile_f64, reported in NOTES).
        r, p = g.shape(), max(g.prob(), F(1, 10 ** 6))
        r = min(r, 10 * p / (1 - p) * 10 ** 6) if p < 1 else r
        return [r, p], F(0), r * (1 - p) / p + 1
    if fam == "hypergeometric":
        n_pop = g.r.randint(1, 80)
        succ, draws = g.r.randint(0, n_pop), g.r.randint(0, n_pop)
        return [F(n_pop), F(succ), F(draws)], F(0), F(max(draws, 1))
    if fam == "discrete_uniform":
        a = g.r.randint(-10, 10)
        return [F(a), F(a + g.r.randint(0, 30))], F(a), F(1)
    if fam == "finite":
        n = g.r.randint(1, 6)
        vals = sorted({F(g.r.randint(-20, 20), g.choice([1, 1, 2, 3])) for _ in range(n)})
        w = [g.r.randint(1, 9) for _ in vals]
        tot = sum(w)
        return [(v, F(wi, tot)) for v, wi in zip(vals, w)], vals[0], F(1)
    raise KeyError(fam)


def fmt_params(fam, params):
    if fam == "finite":
        return ",".join(f"{q(v)}:{q(p)}" for v, p in params)
    return ",".join(q(p) for p in params)


def families(g):
    rows = []
    fams = list(CONT) + DISC
    sets_per_family = 7
    for fam in fams:
        for s in range(sets_per_family):
            params, loc, scl = family_params(g, fam)
            disc = fam in DISC
            base = f"dist.{fam}.{s}"
            ps = fmt_params(fam, params)
            xs = []
            for u in g.r.sample([F(-40), F(-10), F(-3), F(-1), F(-1, 3), F(0), F(1, 7), F(1, 2), F(1), F(2),
                                 F(5), F(20), F(100), F(1, 10 ** 6), F(40)], 3):
                x = loc + scl * u
                if disc and g.r.random() < 0.7:
                    x = F(math.floor(x))
                xs.append(x)
            for i, x in enumerate(xs):
                for m in ("pdf", "cdf", "sf"):
                    rows.append((f"{base}.{m}.{i}", "dist", fam, ps, m, q(x)))
            if not disc and fam in CLOSED_QUANTILE:
                for i, p in enumerate([g.prob(), F(1, 2)]):
                    rows.append((f"{base}.quantile.{i}", "dist", fam, ps, "quantile", q(p)))
            for i in range(2):
                rows.append((f"{base}.quantile_f64.{i}", "dist", fam, ps, "quantile_f64", g.level()))
                rows.append((f"{base}.isf_f64.{i}", "dist", fam, ps, "isf_f64", g.level()))
            for m in ("mean", "variance", "skewness", "kurtosis"):
                rows.append((f"{base}.{m}", "dist", fam, ps, m, "-"))
            if fam not in NO_ENTROPY:
                rows.append((f"{base}.entropy", "dist", fam, ps, "entropy", "-"))
            if fam in CLOSED_QUANTILE:
                rows.append((f"{base}.median", "dist", fam, ps, "median", "-"))
            t = F(g.choice([-1, 1]), g.choice([2, 3, 5, 10])) / scl
            if fam in MGF:
                rows.append((f"{base}.mgf", "dist", fam, ps, "mgf", q(t)))
            if fam in CF:
                rows.append((f"{base}.cf", "dist", fam, ps, "cf", q(t * g.choice([1, 3, 10]))))
    return rows


def f64lu(g, lo, hi):
    return 10 ** g.r.uniform(lo, hi)


def kernels(g):
    rows = []
    n = 0

    def add(target, *args):
        nonlocal n
        rows.append((f"kernel.{target}.{n}", "kernel", target, ",".join(repr(float(a)) for a in args), "-", "-"))
        n += 1

    # Shapes to 10^6 and lattice parameters to 10^10: beyond, the mpmath references of a quantile
    # take minutes (the hunters cover those ranges).
    def shp():
        return g.choice([f64lu(g, -3, 0), f64lu(g, 0, 3), f64lu(g, 3, 6), float(g.r.randint(1, 60)) / 2])

    def lev():
        return g.choice([10 ** -g.r.uniform(0, 300), g.r.random(), 1 - 10 ** -g.r.uniform(1, 15), 0.5, 0.975])

    for _ in range(40):
        a, b = shp(), shp()
        x = g.choice([g.r.random(), 10 ** -g.r.uniform(1, 300), 1 - 10 ** -g.r.uniform(1, 15)])
        add("betainc_regularized", a, b, x)
    for _ in range(40):
        a = shp()
        x = a * g.choice([0.5, 0.9, 1.0, 1.1, 2.0, 1e-3, 1e3])
        add(g.choice(["gammainc_lower_regularized", "gammainc_upper_regularized"]), a, x)
    for fn in ("cdf", "sf", "pdf"):
        for _ in range(12):
            add(f"norm.{fn}", g.r.uniform(-38, 38))
    for fn in ("ppf", "isf"):
        for _ in range(12):
            add(f"norm.{fn}", lev())
    for fn in ("cdf", "sf", "pdf"):
        for _ in range(12):
            add(f"t.{fn}", g.choice([g.r.uniform(-40, 40), 10 ** g.r.uniform(1, 100)]), shp())
    for fn in ("ppf", "isf"):
        for _ in range(12):
            add(f"t.{fn}", lev(), shp())
    for fam, npar in (("gamma", 2), ("chi2", 1), ("beta", 2), ("f", 2)):
        for fn in ("cdf", "sf", "ppf", "isf"):
            for _ in range(12):
                if fam == "gamma":
                    k, th = shp(), 10 ** g.r.uniform(-3, 3)
                    pars = [k, th]
                    x = k * th * g.choice([0.01, 0.5, 0.9, 1.0, 1.1, 2.0, 10.0])
                elif fam == "chi2":
                    k = shp()
                    pars = [k]
                    x = k * g.choice([0.01, 0.5, 0.9, 1.0, 1.1, 2.0, 10.0])
                elif fam == "beta":
                    pars = [shp(), shp()]
                    x = g.choice([g.r.random(), 10 ** -g.r.uniform(1, 100), 1 - 10 ** -g.r.uniform(1, 12)])
                else:
                    pars = [shp(), shp()]
                    x = 10 ** g.r.uniform(-6, 6)
                add(f"{fam}.{fn}", lev() if fn in ("ppf", "isf") else x, *pars)
    for fn in ("cdf", "sf", "ppf", "isf"):
        for _ in range(12):
            nn = float(g.choice([g.r.randint(1, 50), g.r.randint(50, 10 ** 6), int(10 ** g.r.uniform(6, 10))]))
            p = g.choice([g.r.random(), 10 ** -g.r.uniform(1, 30), 1 - 10 ** -g.r.uniform(1, 12)])
            k = float(max(0, math.floor(nn * p + g.choice([-20, -3, 0, 3, 20]) * math.sqrt(nn * p * (1 - p) + 1))))
            add(f"binom.{fn}", lev() if fn in ("ppf", "isf") else k, nn, p)
        for _ in range(12):
            lam = 10 ** g.r.uniform(-3, 10)
            k = float(max(0, math.floor(lam + g.choice([-20, -3, 0, 3, 20]) * math.sqrt(lam))))
            add(f"poisson.{fn}", lev() if fn in ("ppf", "isf") else k, lam)
    return rows


def qlist(xs):
    return ",".join(q(v) for v in xs)


def sample(g, n, kind):
    if kind == "normal":
        mu, sd = F(g.r.randint(-50, 50), 10), F(g.r.randint(1, 30), 10)
        return [F(round(g.r.gauss(float(mu), float(sd)), 2)).limit_denominator(100) for _ in range(n)]
    if kind == "ties":
        return [F(g.r.randint(0, 5)) for _ in range(n)]
    if kind == "ints":
        return [F(g.r.randint(-20, 40)) for _ in range(n)]
    raise KeyError(kind)


def tests(g):
    rows = []
    n = 0

    def add(target, **kw):
        nonlocal n
        rows.append((f"test.{target}.{n}", "test", target, ";".join(f"{k}={v}" for k, v in kw.items()), "-", "-"))
        n += 1

    alts = ["two-sided", "less", "greater"]
    for _ in range(30):
        x = sample(g, g.r.randint(2, 40), g.choice(["normal", "ints"]))
        add("t_test_one_sample", x=qlist(x), mu0=q(F(g.r.randint(-30, 30), 10)), alt=g.choice(alts))
    for _ in range(30):
        x = sample(g, g.r.randint(2, 30), "normal")
        y = sample(g, g.r.randint(2, 30), "normal")
        add("t_test_two_sample", x=qlist(x), y=qlist(y), equal_var=g.choice(["true", "false"]), alt=g.choice(alts))
    for _ in range(20):
        m = g.r.randint(2, 30)
        x = sample(g, m, "normal")
        y = [v + F(g.r.randint(-20, 20), 10) for v in x]
        add("t_test_paired", x=qlist(x), y=qlist(y), alt=g.choice(alts))
    for _ in range(25):
        nn = g.choice([g.r.randint(1, 30), g.r.randint(30, 3000)])
        k = g.r.randint(0, nn)
        add("binomial_test", k=k, n=nn, p0=q(g.prob()), alt=g.choice(alts))
    for _ in range(25):
        t = [[g.r.randint(0, 30) for _ in range(2)] for _ in range(2)]
        if g.r.random() < 0.2:
            t[0][0] += g.r.randint(100, 2000)
        add("fisher_exact", table=":".join(",".join(str(c) for c in r) for r in t), alt=g.choice(alts))
    for _ in range(20):
        nr, nc = g.r.randint(2, 4), g.r.randint(2, 4)
        t = [[g.r.randint(1, 60) for _ in range(nc)] for _ in range(nr)]
        add("chi_square_independence", table=":".join(",".join(str(c) for c in r) for r in t),
            correction=g.choice(["true", "false"]))
    for _ in range(15):
        k = g.r.randint(2, 8)
        obs = [g.r.randint(0, 80) for _ in range(k)]
        if sum(obs) == 0:
            obs[0] = 1
        add("chi_square_goodness_of_fit", observed=qlist(obs))
    for _ in range(20):
        nn = g.r.randint(1, 5000)
        add("z_test_proportion", k=g.r.randint(0, nn), n=nn, p0=q(g.choice([F(1, 2), F(1, 10), F(9, 10), g.prob()])),
            alt=g.choice(alts))
    for _ in range(20):
        x = sample(g, g.r.randint(3, 30), "normal")
        y = [v * F(g.r.randint(-10, 10), 10) + F(g.r.randint(-50, 50), 10) for v in x]
        add("pearson_test", x=qlist(x), y=qlist(y), alt=g.choice(alts))
    for _ in range(25):
        x = sample(g, g.r.randint(1, 20), g.choice(["normal", "ties"]))
        y = sample(g, g.r.randint(1, 20), g.choice(["normal", "ties"]))
        add("mann_whitney_u", x=qlist(x), y=qlist(y), alt=g.choice(alts),
            method=g.choice(["asymptotic_cc", "asymptotic"]))
    for _ in range(15):
        x = sample(g, g.r.randint(1, 8), "normal")
        y = sample(g, g.r.randint(1, 8), "normal")
        if len(set(x + y)) == len(x + y):
            add("mann_whitney_u", x=qlist(x), y=qlist(y), alt=g.choice(alts), method="exact")
    for _ in range(20):
        x = sample(g, g.r.randint(3, 30), g.choice(["normal", "ties"]))
        add("wilcoxon_signed_rank", x=qlist(x), alt=g.choice(alts), method="asymptotic")
    for _ in range(15):
        k = g.r.randint(2, 5)
        groups = [sample(g, g.r.randint(2, 12), g.choice(["normal", "ties"])) for _ in range(k)]
        add("kruskal_wallis", groups=":".join(qlist(gr) for gr in groups))
    for _ in range(15):
        x = sample(g, g.r.randint(4, 30), "normal")
        y = [v * F(g.r.randint(-10, 10), 10) + F(g.r.randint(-30, 30), 10) for v in x]
        add("spearman_test", x=qlist(x), y=qlist(y), alt=g.choice(alts))
    for _ in range(15):
        k = g.r.randint(2, 6)
        groups = [sample(g, g.r.randint(2, 15), "normal") for _ in range(k)]
        add("anova_one_way", groups=":".join(qlist(gr) for gr in groups))
    return rows


def models(g):
    rows = []
    for i in range(24):
        n = g.r.randint(5, 40)
        p = g.r.randint(1, min(4, n - 2))
        cols = [[F(g.r.randint(-50, 50), g.choice([1, 2, 5, 10])) for _ in range(n)] for _ in range(p)]
        beta = [F(g.r.randint(-30, 30), 10) for _ in range(p + 1)]
        y = [beta[0] + sum(b * c[j] for b, c in zip(beta[1:], cols)) + F(g.r.randint(-100, 100), 20)
             for j in range(n)]
        kw = {"y": qlist(y)}
        for k, c in enumerate(cols):
            kw[f"x{k + 1}"] = qlist(c)
        kw["intercept"] = "true"
        rows.append((f"model.ols.{i}", "model", "ols", ";".join(f"{k}={v}" for k, v in kw.items()), "-", "-"))
    return rows


def render(rows):
    ids = set()
    for r in rows:
        assert r[0] not in ids, r[0]
        assert all("\t" not in c and "\n" not in c for c in r), r
        ids.add(r[0])
    return HEADER.format(seed=SEED) + "".join("\t".join(r) + "\n" for r in rows)


def main():
    check = "--check" in sys.argv[1:]
    # One generator per file, so adding cases to one file leaves the others unchanged.
    files = {
        "families.tsv": families(Gen(SEED)),
        "kernels.tsv": kernels(Gen(SEED + 1)),
        "tests.tsv": tests(Gen(SEED + 2)),
        "models.tsv": models(Gen(SEED + 3)),
    }
    bad = 0
    for name, rows in files.items():
        text = render(rows)
        path = OUT / name
        if check:
            if not path.exists() or path.read_text() != text:
                print(f"{path} is not what gen_cases.py generates; rerun it", file=sys.stderr)
                bad = 1
        else:
            OUT.mkdir(exist_ok=True)
            path.write_text(text)
            print(f"{path.relative_to(HERE.parent.parent)}: {len(rows)} cases")
    sys.exit(bad)


if __name__ == "__main__":
    main()
